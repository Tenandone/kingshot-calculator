function replaceHead(html, route, page) {
  const canonical = route.url;
  const alternates = routeAlternates(route.routePath);
  const xDefault = alternates.find(item => item.lang.code === 'en').href;
  const alternateHtml = [
    '  <link rel="alternate" hreflang="x-default" href="' + xDefault + '" />',
    ...alternates.map(item => '  <link rel="alternate" hreflang="' + item.lang.code + '" href="' + item.href + '" />')
  ].join('\n');
  const image = page.image.startsWith('http') ? page.image : ORIGIN + page.image;

  html = html.replace('<!doctype html>', '<!doctype html>\n' + GENERATED_MARKER);
  html = html.replace(/<html\s+lang="[^"]+">/i, '<html lang="' + route.lang.htmlLang + '">');
  html = html.replace(/<script>window\.__V="([^"]+)"<\/script>/, '<script>window.__V="$1";window.__STATIC_LANG=' + escapeJson(route.lang.code) + ';window.__STATIC_ROUTE=' + escapeJson(route.pathname) + '</script>');
  html = html.replace(/<title>[\s\S]*?<\/title>/i, '<title>' + escapeHtml(page.title) + '</title>');
  html = html.replace(/<meta\s+name="description"\s+content="[^"]*"\s*\/>/i, '<meta name="description" content="' + escapeHtml(page.description) + '" />');
  html = html.replace(/<link\s+rel="canonical"\s+href="[^"]*"\s*\/>/i, '<link rel="canonical" href="' + canonical + '" />');
  html = html.replace(/(?:\s*<link\s+rel="alternate"\s+hreflang="[^"]+"\s+href="[^"]*"\s*\/>){5}/i, '\n' + alternateHtml);
  html = html.replace(/<meta\s+property="og:title"\s+content="[^"]*">/i, '<meta property="og:title" content="' + escapeHtml(page.title) + '">');
  html = html.replace(/<meta\s+property="og:description"\s+content="[^"]*">/i, '<meta property="og:description" content="' + escapeHtml(page.description) + '">');
  html = html.replace(/<meta\s+property="og:image"\s+content="[^"]*">/i, '<meta property="og:image" content="' + image + '">');
  html = html.replace(/<meta\s+property="og:url"\s+content="[^"]*">/i, '<meta property="og:url" content="' + canonical + '">');
  html = html.replace(/<meta\s+property="og:type"\s+content="[^"]*">/i, '<meta property="og:type" content="' + page.type + '">');
  html = html.replace(/<meta\s+property="og:locale"\s+content="[^"]*">/i, '<meta property="og:locale" content="' + OG_LOCALE[route.lang.code] + '">');
  html = html.replace(/<meta\s+name="twitter:title"\s+content="[^"]*">/i, '<meta name="twitter:title" content="' + escapeHtml(page.title) + '">');
  html = html.replace(/<meta\s+name="twitter:description"\s+content="[^"]*">/i, '<meta name="twitter:description" content="' + escapeHtml(page.description) + '">');
  html = html.replace(/<meta\s+name="twitter:image"\s+content="[^"]*">/i, '<meta name="twitter:image" content="' + image + '">');
  if (page.type === 'article') {
    html = html.replace(/\s*<meta property="og:image:(?:width|height)"[^>]*>/gi, '');
  }
  const pageSchema = page.schema ? '\n  <script id="ssg-page-schema" type="application/ld+json">' + escapeJson(page.schema) + '</script>' : '';
  html = html.replace('</head>', '  <style>.ssg-initial-content{max-width:860px;margin:0 auto;text-align:center}.ssg-initial-content img{display:block;max-width:100%;height:auto;margin:16px auto}.ssg-initial-content dl{display:grid;grid-template-columns:max-content minmax(0,1fr);gap:8px 16px;max-width:520px;margin:20px auto;text-align:left}.ssg-initial-content dt{font-weight:800}.ssg-initial-content dd{margin:0}.ssg-initial-content ul{max-width:720px;margin:12px auto 24px;text-align:left}.ssg-initial-content nav{text-align:left;font-size:13px}</style>\n  <script id="ssg-breadcrumb-schema" type="application/ld+json">' + escapeJson(breadcrumbJson(route.routePath, route.lang, page.heading)) + '</script>' + pageSchema + '\n</head>');
  return html;
}

function replaceContent(html, route, page) {
  const article = [
    '    <div id="content" class="panel">',
    '      <article class="ssg-initial-content" data-static-seo="true">',
    '        <nav aria-label="Breadcrumb"><a href="' + absoluteUrl('/', route.lang) + '">KingshotData</a></nav>',
    '        <h1>' + escapeHtml(page.heading) + '</h1>',
    '        ' + page.body,
    '      </article>',
    '    </div>',
    '',
    '    <div class="community-promo-stack">'
  ].join('\n');
  return html.replace(/    <div id="content" class="panel">[\s\S]*?    <div class="community-promo-stack">/, article);
}

function cleanPreviousOutputs() {
  if (!fs.existsSync(MANIFEST_FILE)) return;
  const previous = readJson(MANIFEST_FILE);
  for (const relative of previous.files || []) {
    const file = path.resolve(ROOT, relative);
    if (!file.startsWith(ROOT) || !fs.existsSync(file)) continue;
    const head = fs.readFileSync(file, 'utf8').slice(0, 300);
    if (head.includes(GENERATED_MARKER)) fs.rmSync(file);
  }
}

function main() {
  if (!fs.existsSync(TEMPLATE_FILE)) throw new Error('Missing SPA template: ' + TEMPLATE_FILE);
  const template = fs.readFileSync(TEMPLATE_FILE, 'utf8');
  const heroes = readHeroes();
  const events = readEvents();
  const research = readResearch();
  const items = readItems();
  const heroBySlug = new Map(heroes.map(hero => [String(hero.slug), hero]));
  const heroDictionaries = new Map(
    LANGS.map(lang => [lang.code, readJson(path.join(ROOT, 'i18n', lang.folder === 'zh-tw' ? 'zh-TW' : lang.folder, 'heroes.json'))])
  );
  const eventDictionaries = new Map(
    LANGS.map(lang => [lang.code, readJson(path.join(ROOT, 'i18n', lang.folder === 'zh-tw' ? 'zh-TW' : lang.folder, 'events.json'))])
  );
  const researchDictionaries = new Map(
    LANGS.map(lang => [lang.code, readJson(path.join(ROOT, 'i18n', lang.folder === 'zh-tw' ? 'zh-TW' : lang.folder, 'research.json'))])
  );
  const eventBySlug = new Map(events.map(event => [String(event.slug), event]));
  const itemBySlug = new Map(items.map(item => [String(item.slug), item]));
  const itemDictionaries = new Map(
    LANGS.map(lang => [lang.code, readJson(path.join(ROOT, 'i18n', lang.folder === 'zh-tw' ? 'zh-TW' : lang.folder, 'items.json'))])
  );
  const commonDictionaries = new Map(
    LANGS.map(lang => [lang.code, readJson(path.join(ROOT, 'i18n', lang.folder === 'zh-tw' ? 'zh-TW' : lang.folder, 'common.json'))])
  );

  cleanPreviousOutputs();
  const generated = [];
  for (const route of getStaticRoutes()) {
    const heroMatch = route.routePath.match(/^\/hero\/([^/]+)$/);
    const hero = heroMatch ? heroBySlug.get(decodeURIComponent(heroMatch[1])) : null;
    const eventMatch = route.routePath.match(/^\/events\/([^/]+)$/);
    const event = eventMatch ? eventBySlug.get(decodeURIComponent(eventMatch[1])) : null;
    const itemMatch = route.routePath.match(/^\/items\/([^/]+)$/);
    const item = itemMatch ? itemBySlug.get(decodeURIComponent(itemMatch[1])) : null;
    const isResearch = route.routePath === '/research' || route.routePath.startsWith('/research/');
    const isItems = route.routePath === '/items' || route.routePath.startsWith('/items/');
    const page = isItems
      ? itemPage(route.routePath, item, route.lang, items, itemDictionaries.get(route.lang.code), eventDictionaries.get(route.lang.code))
      : isResearch
      ? researchPage(route.routePath, route.lang, research, researchDictionaries.get(route.lang.code))
      : hero
      ? heroPage(hero, route.lang, heroDictionaries.get(route.lang.code), heroes)
      : event
        ? eventPage(event, route.lang, eventDictionaries.get(route.lang.code), heroDictionaries.get(route.lang.code), heroes, events)
        : genericPage(route.routePath, route.lang, heroDictionaries.get(route.lang.code), heroes, events, eventDictionaries.get(route.lang.code), commonDictionaries.get(route.lang.code));
    let html = replaceHead(template, route, page);
    html = replaceContent(html, route, page);
    fs.mkdirSync(path.dirname(route.file), { recursive: true });
    fs.writeFileSync(route.file, html, 'utf8');
    generated.push(path.relative(ROOT, route.file).replace(/\\/g, '/'));
  }

  fs.writeFileSync(MANIFEST_FILE, JSON.stringify({ files: generated }, null, 2) + '\n', 'utf8');
  console.log('Generated ' + generated.length + ' static SPA routes.');
}

main();
