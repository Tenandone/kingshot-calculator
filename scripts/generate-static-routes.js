function escapeHtml(value) {
  return String(value == null ? '' : value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function escapeJson(value) {
  return JSON.stringify(value).replace(/</g, '\\u003c');
}

function translated(value, dictionary, fallback) {
  if (!value) return fallback || '';
  const key = String(value).trim();
  return Object.prototype.hasOwnProperty.call(dictionary, key) ? dictionary[key] : (fallback || key);
}

function truncate(value, max) {
  const text = String(value || '').replace(/\s+/g, ' ').trim();
  return text.length > max ? text.slice(0, max - 1).trimEnd() + '…' : text;
}

function routeAlternates(routePath) {
  return LANGS.map(lang => ({ lang, href: absoluteUrl(routePath, lang) }));
}

function breadcrumbJson(routePath, lang, title) {
  const homeName = SITE_NAME[lang.code];
  const sectionName = routePath.startsWith('/hero/')
    ? (COPY[lang.code]['/heroes'] || COPY.en['/heroes'])[2]
    : title;
  const items = [
    { '@type': 'ListItem', position: 1, name: homeName, item: absoluteUrl('/', lang) }
  ];
  if (routePath.startsWith('/hero/')) {
    items.push({ '@type': 'ListItem', position: 2, name: sectionName, item: absoluteUrl('/heroes', lang) });
    items.push({ '@type': 'ListItem', position: 3, name: title, item: absoluteUrl(routePath, lang) });
  } else if (routePath !== '/') {
    items.push({ '@type': 'ListItem', position: 2, name: title, item: absoluteUrl(routePath, lang) });
  }
  return { '@context': 'https://schema.org', '@type': 'BreadcrumbList', itemListElement: items };
}

function eventCopy(dictionary, slug) {
  return dictionary && dictionary.records && dictionary.records[slug] ? dictionary.records[slug] : {};
}

function genericPage(routePath, lang, dictionary, heroes, events, eventDictionary) {
  const entry = COPY[lang.code][routePath] || COPY.en[routePath];
  const [title, description, heading] = entry;
  let body = '<p>' + escapeHtml(description) + '</p>';
  if (routePath === '/heroes') {
    body += '<h2>' + escapeHtml(lang.code === 'ko' ? '영웅 목록' : lang.code === 'ja' ? '英雄一覧' : lang.code === 'zh-TW' ? '英雄列表' : 'Hero List') + '</h2><ul>';
    body += heroes.map(hero => {
      const name = translated(hero.title, dictionary, hero.name || hero.slug);
      return '<li><a href="' + absoluteUrl('/hero/' + encodeURIComponent(hero.slug), lang) + '">' + escapeHtml(name) + '</a></li>';
    }).join('');
    body += '</ul>';
  } else if (routePath === '/events') {
    body = '<p>' + escapeHtml(eventDictionary.intro || description) + '</p><h2>' + escapeHtml(eventDictionary.title || heading) + '</h2><ul>';
    body += events.map(event => {
      const copy = eventCopy(eventDictionary, event.slug);
      return '<li><a href="' + absoluteUrl('/events/' + encodeURIComponent(event.slug), lang) + '">' + escapeHtml(copy.title || event.slug) + '</a> - ' + escapeHtml(copy.summary || '') + '</li>';
    }).join('');
    body += '</ul>';
  }
  return {
    title: routePath === '/' ? title : title + ' | ' + TITLE_SITE_NAME[lang.code],
    description,
    heading,
    image: '/img/kingshotdata-og-v5.png',
    type: 'website',
    body
  };
}

function eventPage(event, lang, eventDictionary, heroDictionary, heroes, events) {
  const copy = eventCopy(eventDictionary, event.slug);
  const labels = eventDictionary.labels || {};
  const name = copy.title || event.slug;
  const summary = copy.summary || '';
  const type = (eventDictionary.types || {})[event.type] || event.type;
  const recurrence = (eventDictionary.recurrence || {})[event.recurrence] || '';
  const unlock = (eventDictionary.unlock || {})[event.unlock] || '';
  const duration = event.durationDays
    ? event.durationDays + ' ' + (labels.days || 'days')
    : event.durationHours
      ? event.durationHours + ' ' + (labels.hours || 'hours')
      : '';
  const facts = [
    [labels.type || 'Event type', type],
    [labels.duration || 'Duration', duration],
    [labels.recurrence || 'Recurrence', recurrence],
    [labels.unlock || 'Unlock', unlock],
    [labels.lastVerified || 'Last verified', event.verifiedAt || '2026-09-18']
  ].filter(row => row[1]);
  const eventBySlug = new Map(events.map(item => [item.slug, item]));
  const heroBySlug = new Map(heroes.map(item => [item.slug, item]));
  const relatedEvents = (event.relatedEvents || []).map(slug => {
    const related = eventBySlug.get(slug);
    const title = eventCopy(eventDictionary, slug).title || slug;
    return related ? '<a href="' + absoluteUrl('/events/' + encodeURIComponent(slug), lang) + '">' + escapeHtml(title) + '</a>' : '';
  }).filter(Boolean);
  const relatedHeroes = (event.relatedHeroes || []).map(slug => {
    const hero = heroBySlug.get(slug);
    if (!hero) return '';
    const title = translated(hero.title, heroDictionary, hero.name || slug);
    return '<a href="' + absoluteUrl('/hero/' + encodeURIComponent(slug), lang) + '">' + escapeHtml(title) + '</a>';
  }).filter(Boolean);
  const guidePrefix = '/' + lang.folder + '/guides/';
  const relatedGuides = (event.relatedGuides || []).map(slug => '<a href="' + guidePrefix + encodeURIComponent(slug) + '.html">' + escapeHtml(name) + '</a>');

  let body = '<p>' + escapeHtml(summary) + '</p>';
  body += '<h2>' + escapeHtml(labels.quickFacts || 'Quick Facts') + '</h2><dl>';
  body += facts.map(row => '<dt>' + escapeHtml(row[0]) + '</dt><dd>' + escapeHtml(String(row[1])) + '</dd>').join('');
  body += '</dl>';
  if (copy.answerTitle && copy.answer) body += '<h2>' + escapeHtml(copy.answerTitle) + '</h2><p>' + escapeHtml(copy.answer) + '</p>';
  if (relatedEvents.length) body += '<h2>' + escapeHtml(labels.relatedEvents || 'Related events') + '</h2><p>' + relatedEvents.join(' · ') + '</p>';
  if (relatedHeroes.length) body += '<h2>' + escapeHtml(labels.relatedHeroes || 'Related heroes') + '</h2><p>' + relatedHeroes.join(' · ') + '</p>';
  if (relatedGuides.length) body += '<h2>' + escapeHtml(labels.relatedGuides || 'Related guides') + '</h2><p>' + relatedGuides.join(' · ') + '</p>';
  body += '<h2>' + escapeHtml(labels.verification || 'Data verification') + '</h2>';
  body += '<p>' + escapeHtml(labels.crossVerified || 'Cross-verified') + ' · ' + escapeHtml(event.verifiedAt || '2026-09-18') + '</p><ul>';
  body += (event.sources || []).map(source => '<li><a href="' + escapeHtml(source.url) + '" rel="nofollow noopener">' + escapeHtml(source.name) + '</a></li>').join('');
  body += '</ul>';

  return {
    title: name + ' | ' + TITLE_SITE_NAME[lang.code],
    description: truncate(summary, 155),
    heading: name,
    image: '/img/kingshotdata-og-v5.png',
    type: 'article',
    body,
    schema: {
      '@context': 'https://schema.org',
      '@type': 'WebPage',
      name,
      description: summary,
      url: absoluteUrl('/events/' + encodeURIComponent(event.slug), lang),
      dateModified: event.verifiedAt || '2026-09-18',
      isPartOf: { '@type': 'WebSite', name: 'KingshotData', url: ORIGIN + '/' }
    }
  };
}

function heroPage(hero, lang, dictionary, heroes) {
  const name = translated(hero.title, dictionary, hero.name || hero.slug);
  const subtitle = translated(hero.subtitle, dictionary, '');
  const summary = translated(hero.summary, dictionary, subtitle);
  const unit = translated(hero.unit, dictionary, '');
  const sources = (hero.sources || []).map(value => translated(value, dictionary, '')).filter(Boolean);
  const stats = [];
  const skills = [];

  for (const group of [hero.conquest, hero.expedition]) {
    if (!group) continue;
    for (const stat of group.stats || []) {
      stats.push(translated(stat.label, dictionary, stat.label) + ': ' + stat.value);
    }
    for (const skill of group.skills || []) {
      const text = translated(skill.desc, dictionary, '');
      if (text) skills.push(text);
    }
  }

  const related = heroes
    .filter(item => item.slug !== hero.slug && item.generation === hero.generation)
    .map(item => translated(item.title, dictionary, item.name || item.slug));
  const generationLabel = lang.code === 'ko' ? '세대' : lang.code === 'ja' ? '世代' : lang.code === 'zh-TW' ? '世代' : 'Generation';
  const sourceLabel = lang.code === 'ko' ? '획득처' : lang.code === 'ja' ? '入手方法' : lang.code === 'zh-TW' ? '取得方式' : 'Acquisition';
  const skillsLabel = lang.code === 'ko' ? '주요 스킬' : lang.code === 'ja' ? '主要スキル' : lang.code === 'zh-TW' ? '主要技能' : 'Key Skills';
  const relatedLabel = lang.code === 'ko' ? '같은 세대 영웅' : lang.code === 'ja' ? '同世代の英雄' : lang.code === 'zh-TW' ? '同世代英雄' : 'Heroes from the same generation';
  const description = truncate([summary, generationLabel + ' ' + hero.generation, unit, sources.join(', ')].filter(Boolean).join(' · '), 155);
  const detailItems = [generationLabel + ' ' + hero.generation, unit].filter(Boolean);

  let body = '';
  if (hero.image) body += '<img src="' + escapeHtml(hero.image) + '" alt="' + escapeHtml(name) + '" width="220" height="220" loading="eager">';
  if (subtitle) body += '<p class="ssg-subtitle">' + escapeHtml(subtitle) + '</p>';
  body += '<p>' + escapeHtml(summary) + '</p>';
  body += '<dl><dt>' + escapeHtml(generationLabel) + '</dt><dd>' + escapeHtml(String(hero.generation || '')) + '</dd>';
  if (unit) body += '<dt>' + escapeHtml(lang.code === 'ko' ? '병종' : lang.code === 'ja' ? '兵種' : lang.code === 'zh-TW' ? '兵種' : 'Unit Type') + '</dt><dd>' + escapeHtml(unit) + '</dd>';
  body += '</dl>';
  if (sources.length) body += '<h2>' + escapeHtml(sourceLabel) + '</h2><ul>' + sources.map(value => '<li>' + escapeHtml(value) + '</li>').join('') + '</ul>';
  if (stats.length) body += '<h2>' + escapeHtml(lang.code === 'ko' ? '주요 능력치' : lang.code === 'ja' ? '主要能力値' : lang.code === 'zh-TW' ? '主要屬性' : 'Key Stats') + '</h2><ul>' + stats.map(value => '<li>' + escapeHtml(value) + '</li>').join('') + '</ul>';
  if (skills.length) body += '<h2>' + escapeHtml(skillsLabel) + '</h2><ul>' + skills.map(value => '<li>' + escapeHtml(value) + '</li>').join('') + '</ul>';
  if (related.length) body += '<h2>' + escapeHtml(relatedLabel) + '</h2><p>' + related.map(escapeHtml).join(' · ') + '</p>';

  return {
    title: name + ' | ' + TITLE_SITE_NAME[lang.code],
    description,
    heading: name,
    image: hero.image || '/img/kingshotdata-og-v5.png',
    type: 'article',
    body,
    keywords: detailItems.join(', ')
  };
}

function replaceHead(html, route, page) {
  const canonical = route.url;
  const alternates = routeAlternates(route.routePath);
  const xDefault = alternates.find(item => item.lang.code === 'en').href;
  const alternateHtml = [
    '  <link rel="alternate" hreflang="x-default" href="' + xDefault + '" />',
    ...alternates.map(item => '  <link rel="alternate" hreflang="' + item.lang.code + '" href="' + item.href + '" />')
  ].join('\n');
  const image = page.image.startsWith('http') ? page.image : ORIGIN + page.image;

  html = html.replace('<!doctype html>', '<!doctype html>\n' + GENERATED_MARKER);
  html = html.replace(/<html\s+lang="[^"]+">/i, '<html lang="' + route.lang.htmlLang + '">');
  html = html.replace(/<script>window\.__V="([^"]+)"<\/script>/, '<script>window.__V="$1";window.__STATIC_LANG=' + escapeJson(route.lang.code) + ';window.__STATIC_ROUTE=' + escapeJson(route.pathname) + '</script>');
  html = html.replace(/<title>[\s\S]*?<\/title>/i, '<title>' + escapeHtml(page.title) + '</title>');
  html = html.replace(/<meta\s+name="description"\s+content="[^"]*"\s*\/>/i, '<meta name="description" content="' + escapeHtml(page.description) + '" />');
  html = html.replace(/<link\s+rel="canonical"\s+href="[^"]*"\s*\/>/i, '<link rel="canonical" href="' + canonical + '" />');
  html = html.replace(/(?:\s*<link\s+rel="alternate"\s+hreflang="[^"]+"\s+href="[^"]*"\s*\/>){5}/i, '\n' + alternateHtml);
  html = html.replace(/<meta\s+property="og:title"\s+content="[^"]*">/i, '<meta property="og:title" content="' + escapeHtml(page.title) + '">');
  html = html.replace(/<meta\s+property="og:description"\s+content="[^"]*">/i, '<meta property="og:description" content="' + escapeHtml(page.description) + '">');
  html = html.replace(/<meta\s+property="og:image"\s+content="[^"]*">/i, '<meta property="og:image" content="' + image + '">');
  html = html.replace(/<meta\s+property="og:url"\s+content="[^"]*">/i, '<meta property="og:url" content="' + canonical + '">');
  html = html.replace(/<meta\s+property="og:type"\s+content="[^"]*">/i, '<meta property="og:type" content="' + page.type + '">');
  html = html.replace(/<meta\s+property="og:locale"\s+content="[^"]*">/i, '<meta property="og:locale" content="' + OG_LOCALE[route.lang.code] + '">');
  html = html.replace(/<meta\s+name="twitter:title"\s+content="[^"]*">/i, '<meta name="twitter:title" content="' + escapeHtml(page.title) + '">');
  html = html.replace(/<meta\s+name="twitter:description"\s+content="[^"]*">/i, '<meta name="twitter:description" content="' + escapeHtml(page.description) + '">');
  html = html.replace(/<meta\s+name="twitter:image"\s+content="[^"]*">/i, '<meta name="twitter:image" content="' + image + '">');
  if (page.type === 'article') {
    html = html.replace(/\s*<meta property="og:image:(?:width|height)"[^>]*>/gi, '');
  }
  const pageSchema = page.schema ? '\n  <script id="ssg-page-schema" type="application/ld+json">' + escapeJson(page.schema) + '</script>' : '';
  html = html.replace('</head>', '  <style>.ssg-initial-content{max-width:860px;margin:0 auto;text-align:center}.ssg-initial-content img{display:block;max-width:100%;height:auto;margin:16px auto}.ssg-initial-content dl{display:grid;grid-template-columns:max-content minmax(0,1fr);gap:8px 16px;max-width:520px;margin:20px auto;text-align:left}.ssg-initial-content dt{font-weight:800}.ssg-initial-content dd{margin:0}.ssg-initial-content ul{max-width:720px;margin:12px auto 24px;text-align:left}.ssg-initial-content nav{text-align:left;font-size:13px}</style>\n  <script id="ssg-breadcrumb-schema" type="application/ld+json">' + escapeJson(breadcrumbJson(route.routePath, route.lang, page.heading)) + '</script>' + pageSchema + '\n</head>');
  return html;
}

function replaceContent(html, route, page) {
  const article = [
    '    <div id="content" class="panel">',
    '      <article class="ssg-initial-content" data-static-seo="true">',
    '        <nav aria-label="Breadcrumb"><a href="' + absoluteUrl('/', route.lang) + '">KingshotData</a></nav>',
    '        <h1>' + escapeHtml(page.heading) + '</h1>',
    '        ' + page.body,
    '      </article>',
    '    </div>',
    '',
    '    <div class="community-promo-stack">'
  ].join('\n');
  return html.replace(/    <div id="content" class="panel">[\s\S]*?    <div class="community-promo-stack">/, article);
}

function cleanPreviousOutputs() {
  if (!fs.existsSync(MANIFEST_FILE)) return;
  const previous = readJson(MANIFEST_FILE);
  for (const relative of previous.files || []) {
    const file = path.resolve(ROOT, relative);
    if (!file.startsWith(ROOT) || !fs.existsSync(file)) continue;
    const head = fs.readFileSync(file, 'utf8').slice(0, 300);
    if (head.includes(GENERATED_MARKER)) fs.rmSync(file);
  }
}

function main() {
  if (!fs.existsSync(TEMPLATE_FILE)) throw new Error('Missing SPA template: ' + TEMPLATE_FILE);
  const template = fs.readFileSync(TEMPLATE_FILE, 'utf8');
  const heroes = readHeroes();
  const events = readEvents();
  const heroBySlug = new Map(heroes.map(hero => [String(hero.slug), hero]));
  const heroDictionaries = new Map(
    LANGS.map(lang => [lang.code, readJson(path.join(ROOT, 'i18n', lang.folder === 'zh-tw' ? 'zh-TW' : lang.folder, 'heroes.json'))])
  );
  const eventDictionaries = new Map(
    LANGS.map(lang => [lang.code, readJson(path.join(ROOT, 'i18n', lang.folder === 'zh-tw' ? 'zh-TW' : lang.folder, 'events.json'))])
  );
  const eventBySlug = new Map(events.map(event => [String(event.slug), event]));

  cleanPreviousOutputs();
  const generated = [];
  for (const route of getStaticRoutes()) {
    const heroMatch = route.routePath.match(/^\/hero\/([^/]+)$/);
    const hero = heroMatch ? heroBySlug.get(decodeURIComponent(heroMatch[1])) : null;
    const eventMatch = route.routePath.match(/^\/events\/([^/]+)$/);
    const event = eventMatch ? eventBySlug.get(decodeURIComponent(eventMatch[1])) : null;
    const page = hero
      ? heroPage(hero, route.lang, heroDictionaries.get(route.lang.code), heroes)
      : event
        ? eventPage(event, route.lang, eventDictionaries.get(route.lang.code), heroDictionaries.get(route.lang.code), heroes, events)
        : genericPage(route.routePath, route.lang, heroDictionaries.get(route.lang.code), heroes, events, eventDictionaries.get(route.lang.code));
    let html = replaceHead(template, route, page);
    html = replaceContent(html, route, page);
    fs.mkdirSync(path.dirname(route.file), { recursive: true });
    fs.writeFileSync(route.file, html, 'utf8');
    generated.push(path.relative(ROOT, route.file).replace(/\\/g, '/'));
  }

  fs.writeFileSync(MANIFEST_FILE, JSON.stringify({ files: generated }, null, 2) + '\n', 'utf8');
  console.log('Generated ' + generated.length + ' static SPA routes.');
}

main();
